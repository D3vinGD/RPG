#ifndef COLORS_H
#define COLORS_H

#define RESET   "\033[0m"      /* Restablecer color */
#define RED     "\033[31m"     /* Rojo */
#define GREEN   "\033[32m"     /* Verde */
#define YELLOW  "\033[33m"     /* Amarillo */
#define CYAN    "\033[36m"     /* Cian (azul verdoso) */
#define MAGENTA "\033[35m"     /* Magenta */
#define ROSA    "\033[38;5;206m"   /* Rosa */
#define ORANGE  "\033[38;5;208m"   /* Naranja */
#define GRAY    "\033[90m"      /* Gris */
#define GOLDEN_YELLOW "\033[33;1m"   /* Amarillo dorado */

#endif  // COLORS_H